test('context evidence, source hashes and explicit non-UTF8 errors use real indexes',async({page,request})=>{
 const project=join(process.env.CODEWEAVE_BROWSER_WORKDIR!,'project'),main=join(project,'main.cpp'),header=join(project,'context_settings.hpp');
 const before='#pragma once\ninline constexpr unsigned browser_scale=2;\nenum class BrowserLevel:unsigned { value=3 };\n';
 const after='#pragma once\ninline constexpr unsigned browser_scale=7;\nenum class BrowserLevel:unsigned { value=5 };\n';
 const oldHash=createHash('sha256').update(before).digest('hex'),newHash=createHash('sha256').update(after).digest('hex');
 await writeFile(header,before);
 await writeFile(main,'#include "context_settings.hpp"\n'+await readFile(main,'utf8')+'\nunsigned browser_context_consumer(){return browser_scale*static_cast<unsigned>(BrowserLevel::value);}\n');
 await page.goto('/');
 async function advance(){
  const generation=(await(await request.get('/api/workspace')).json()).generation;
  await expect(page.getByRole('button',{name:'刷新工作区',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'刷新工作区',exact:true}).click();
  await expect.poll(async()=> (await(await request.get('/api/workspace')).json()).generation,{timeout:45000}).toBe(generation+1);
  const finished=await(await request.get('/api/workspace')).json();
  await expect(page.locator('.attempt code')).toHaveText(finished.last_attempt.request_id);
  await expect(page.locator('.attempt strong')).toHaveText('published');
  return finished.latest_successful_index as string;
 }
 const baseline=await advance();await writeFile(header,after);const current=await advance();
 await page.getByRole('button',{name:'比较上次成功与本次结果'}).click();
 await expect(page.getByLabel('Left comparison index')).toHaveValue(baseline);
 await expect(page.getByLabel('Right comparison index')).toHaveValue(current);
 await page.getByLabel('Change group').selectOption('symbols');
 const context=page.locator('.change-list button').filter({hasText:'definition_context_changed'}).filter({hasText:'browser_context_consumer'});
 await expect(context).toHaveCount(1);await context.click();
 const evidence=page.locator('.change-evidence details');await evidence.locator('summary').click();
 await expect(evidence).toContainText('context_settings.hpp');await expect(evidence).toContainText(oldHash);await expect(evidence).toContainText(newHash);
 const response=await(await request.get('/api/diff/symbols',{params:{left:baseline,right:current,limit:200}})).json();
 const actual=response.items.find((e:{after:{name:string}})=>e.after.name==='browser_context_consumer');
 expect(actual.odr_hint.before).toBe(actual.odr_hint.after);expect(actual.odr_hint.authoritative).toBe(false);
 expect(actual.changed_inputs).toEqual([{kind:'input',path:header,before_sha256:oldHash,after_sha256:newHash}]);
 await page.getByLabel('Change group').selectOption('files');
 await page.locator('.change-list button').filter({hasText:'context_settings.hpp'}).click();
 await expect(page.locator('.source-diff .view-lines')).toContainText(['browser_scale=2','browser_scale=7']);
 await page.getByText('两侧源码哈希与字节范围',{exact:true}).click();
 await expect(page.locator('.source-diff')).toContainText(oldHash);await expect(page.locator('.source-diff')).toContainText(newHash);
 // The indexed bytes remain valid facts; an undecodable window is an explicit
 // source error, and switching to a valid historical buffer still works.
 const saved=await readFile(main);const at=saved.indexOf(Buffer.from('unsigned browser_context_consumer'));
 expect(at).toBeGreaterThan(0);
 await writeFile(main,Buffer.concat([saved.subarray(0,at),Buffer.from('// owned invalid \xff\n','latin1'),saved.subarray(at)]));
 const invalid=await advance();await page.getByLabel('Snapshot identity').selectOption(invalid);
 await page.getByLabel('Function or method').fill('browser_context_consumer');await page.locator('.result').click();
 await expect(page.getByRole('alert').filter({hasText:'source_not_utf8'})).toBeVisible();
 await page.getByLabel('Snapshot identity').selectOption(current);
 await page.locator('.result').click();
 await expect(page.locator('.source-section .view-lines')).toContainText('browser_context_consumer');
 await expect(page.locator('.source-heading')).toContainText(current);await expect(page.locator('.source-heading')).toContainText('SHA-256');
 await expect(page.locator('.source-section .view-lines')).not.toContainText('\uFFFD');
});
